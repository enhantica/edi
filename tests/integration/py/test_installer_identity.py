@pytest.mark.parametrize(('system', 'suffix'), [('macos', '.dmg'), ('windows', '.exe')])
def test_download_is_one_native_installer(tmp_path, monkeypatch, system, suffix):
    monkeypatch.setattr(PACKAGE, 'SYSTEM', system)
    installer = tmp_path / ('EasyDiffraction.app' if system == 'macos' else 'EasyDiffraction.exe')
    if system == 'macos':
        installer.mkdir()
        (installer / 'payload').write_bytes(b'installer app')
    else:
        installer.write_bytes(b'MZfixture')
    commands = []

    def external(args, **_kwargs):
        commands.append(list(map(str, args)))
        if str(args[0]) == 'hdiutil' and 'create' in args:
            folder = Path(args[args.index('-srcfolder') + 1])
            assert (folder / 'EasyDiffraction.app/payload').read_bytes() == b'installer app', (
                'ADR-0091: the disk image receives the intact installer app'
            )
            Path(args[-1]).write_bytes(b'disk image fixture')
        elif str(args[0]) == 'ditto' and len(args) == 3:
            shutil.copytree(args[1], args[2])
        elif str(args[0]) == 'ditto':
            with zipfile.ZipFile(args[-1], 'w') as archive:
                archive.writestr('EasyDiffraction.app/payload', b'installer app')

    monkeypatch.setattr(PACKAGE, 'run', external)
    # Archive membership is not used as evidence: only the real packager's returned delivery path.
    deliver = getattr(PACKAGE, 'deliver_installer', None) or PACKAGE.archive_installer
    result = deliver(installer, None, ad_hoc=False)
    assert result.suffix == suffix, (
        'ADR-0091: macOS delivers a DMG and Windows delivers a standalone EXE '
        'without unpacking a ZIP'
    )
    if system == 'macos':
        assert any('hdiutil' in command[0] and 'create' in command for command in commands), (
            'ADR-0091: the macOS download is created as a disk image containing the installer app'
        )
    else:
        assert result.read_bytes() == b'MZfixture', (
            'ADR-0091: the Windows download retains the self-contained installer executable bytes'
        )


