def reaches_cleanup(condition, context):
    condition = str(condition or 'true')
    # Actions adds success() when no explicit status function appears.
    status = re.search(r'\b(?:always|success|failure|cancelled)\s*\(', condition)
    return bool(value(condition, context)) and (bool(status) or context['success()'])


@pytest.mark.parametrize('workflow', ['installers.yml', 'release-plan.yml', 'release-publish.yml'])
def test_failed_release_workflow_reaches_owned_draft_cleanup(workflow):
    document = yaml.safe_load((ROOT / '.github/workflows' / workflow).read_text())
    cleanups = [
        (job, step)
        for job in document['jobs'].values()
        for step in job.get('steps', [])
        if '--withdraw' in step.get('run', '')
    ]
    assert cleanups, 'Release hygiene: each release workflow cleans its owned draft when it fails'
    for outcome in ('failure', 'cancelled'):
        context = {
            'success()': False,
            'failure()': outcome == 'failure',
            'cancelled()': outcome == 'cancelled',
            'github.event_name': 'workflow_dispatch',
            'github.ref': 'refs/heads/main',
            'github.repository': 'enhantica/edi',
            'github.event.pull_request.head.repo.fork': False,
            'inputs.prepare_preview_release': True,
            'inputs.preview_run': '',
            'needs.preview-version.result': 'success',
            'needs.installers.result': outcome,
            'needs.draft-preview-release.result': 'skipped',
        }
        entered = {**context, 'success()': True, 'failure()': False, 'cancelled()': False}
        assert any(
            reaches_cleanup(job.get('if'), context if job.get('needs') else entered)
            and reaches_cleanup(step.get('if'), entered if job.get('needs') else context)
            for job, step in cleanups
        ), 'Release hygiene: actual cleanup job and step guards admit failure and cancellation'
        assert not reaches_cleanup('false && always()', context), (
            'Release hygiene: merely mentioning always() cannot make disabled cleanup reachable'
        )
        assert not reaches_cleanup('true', context), (
            'Release hygiene: a cleanup with the implicit success guard is skipped after failure'
        )


@pytest.mark.parametrize('prerelease', [False, True])
def test_draft_cleanup_preserves_other_sources_channels_and_published_releases(
    monkeypatch, prerelease
):
    plan = load('tools/release/plan.py')
    with mock.patch.dict(sys.modules, {'plan': plan}):
        prepare = load('tools/release/prepare.py')
    own = 'a' * 40

    def release(identifier, *, commit=own, channel=prerelease, draft=True):
        return {
            'id': identifier,
            'target_commitish': commit,
            'prerelease': channel,
            'draft': draft,
            'tag_name': f'v2026.11.{identifier}',
            'assets': [],
            'body': '',
        }

    records = [
        release(31),
        release(32, commit='b' * 40),
        release(33, channel=not prerelease),
        release(34, draft=False),
    ]
    monkeypatch.setattr(prepare, 'list_releases', lambda *_args: records)
    calls = []

    def github(command, **_kwargs):
        calls.append(list(map(str, command)))
        return subprocess.CompletedProcess(command, 0, b'{}', b'')

    monkeypatch.setattr(prepare.subprocess, 'run', github)
    tags = prepare.withdraw_drafts('example/fixture', own, prerelease=prerelease)
    assert tags == ['v2026.11.31'], (
        'Release hygiene: only an unpublished draft for this source and channel is withdrawn'
    )
    assert (
        len(calls) == 1
        and 'DELETE' in calls[0]
        and calls[0][-1] == 'repos/example/fixture/releases/31'
    ), (
        'Release hygiene: cleanup deletes the owned draft by id '
        'and never a published or unrelated release'
    )


@pytest.mark.parametrize('system', ['windows', 'macos'])
def test_release_signs_assistant_executables_outside_the_app(tmp_path, monkeypatch, system):
    monkeypatch.syspath_prepend(str(ROOT / 'tools/installer'))
    build = load('tools/installer/build.py')
    monkeypatch.setattr(build, 'SYSTEM', system)
    monkeypatch.setattr(sys.modules['package'], 'SYSTEM', system)
    monkeypatch.setenv('EDI_CODESIGN', '1')
    monkeypatch.setenv('EDI_CODESIGN_MAC_IDENTITY', 'Developer ID Application: Fixture')
    monkeypatch.setenv('EDI_CODESIGN_WIN_KEYPAIR_ALIAS', 'fixture-key')
    sdk = tmp_path / 'sdk'
    (sdk / 'include/crysta').mkdir(parents=True)
    (sdk / 'include/crysta/model.hpp').write_text('')
    work = tmp_path / 'work'
    stage = work / 'stage'
    stage.mkdir(parents=True)
    runtime = stage / 'libexec/edi/codex'
    runtime.mkdir(parents=True)
    suffix = '.exe' if system == 'windows' else ''
    helpers = [runtime / (name + suffix) for name in ['codex', 'codex-exec']]
    magic = b'MZ\x00\x00' if system == 'windows' else b'\xcf\xfa\xed\xfe'
    for helper in helpers:
        helper.write_bytes(magic + b'fixture executable')
    # The build owns stage creation. Simulate installation only when CMake is invoked.
    stage.rename(work / 'staged-fixture')
    signed = []

    def external(args, **_kwargs):
        words = list(map(str, args))
        if '--install' in words:
            (work / 'staged-fixture').rename(stage)
        if any('codesign' in word or 'smctl' in word for word in words):
            signed.extend(words)

    monkeypatch.setattr(build, 'run', external)
    monkeypatch.setattr(
        build,
        'release_identity',
        lambda *_args: {
            'version': None,
            'plan': None,
            'commit': 'a' * 40,
            'history_hash': None,
        },
    )
    monkeypatch.setattr(build, 'acquire_sdk', lambda *_args: sdk)
    monkeypatch.setattr(build, 'resolve_qt_prefix', lambda *_args: tmp_path / 'qt')
    for name in [
        'copy_windows_compiler_runtime',
        'collect_notices',
        'drop_macos_build_rpaths',
        'check_macos_load_paths',
        'sign_macos_app',
        'verify_assistant_payload',
    ]:
        monkeypatch.setattr(build, name, lambda *_args: None)
    monkeypatch.setattr(build, 'sign_windows', lambda path: signed.append(str(path)))
    monkeypatch.setattr(build, 'audit_bundle', lambda *_args: {})
    monkeypatch.setattr(build, 'crysta_commit', lambda *_args: 'b' * 40)
    monkeypatch.setattr(build, 'sha256', lambda *_args: 'c' * 64)
    build.build(sdk, work, None, None)
    assert all(str(helper) in signed for helper in helpers), (
        'ADR-0091: every assistant helper outside the app bundle is signed in a release build'
    )


