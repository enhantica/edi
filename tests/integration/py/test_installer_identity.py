@pytest.mark.parametrize('system', ['windows', 'macos', 'linux'])
def test_metadata_preserves_existing_component_updates(tmp_path, monkeypatch, system):
    monkeypatch.setattr(PACKAGE, 'SYSTEM', system)
    meta = tmp_path / 'meta'
    config = tmp_path / 'config'
    meta.mkdir()
    config.mkdir()
    PACKAGE.write_metadata(config, meta, '2026.11.23', None)
    app = parse_metadata(meta / 'package.xml')
    assert 'org.easyscience.edi' in (app.findtext('Replaces') or '').split(','), (
        'ADR-0091: the renamed application component replaces the installed old component'
    )
    PACKAGE.write_assistant_metadata(meta, '2026.11.23')
    assistant = parse_metadata(meta / 'package.xml')
    assert 'org.easyscience.edi.assistant' in (assistant.findtext('Replaces') or '').split(','), (
        'ADR-0091: the renamed optional assistant updates its old component in place'
    )
    assert assistant.findtext('Dependencies') == 'org.easydiffraction.app', (
        'ADR-0091: the optional assistant depends on the new application component'
    )


