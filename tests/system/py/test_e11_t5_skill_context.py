"""Actual shipped skill bytes in one consented context, accepted packet710585daf.

The resource identity oracle is independently hashing the shipped original file,
not a content string generated by core or a scientific value returned by a model.
Scientific skill accuracy requires separate primary-reference/conversion evidence.
"""

from __future__ import annotations

import hashlib
import importlib.util
import json
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[3]
_spec = importlib.util.spec_from_file_location(
    'skills_protocol', ROOT / 'tests/integration/py/test_e11_t5_assistant_protocol.py'
)
protocol = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(protocol)
host = protocol.host
IDS = ['project-assistance', 'fullprof-intake', 'gsas-intake']


def shipped(identity):
    folder = ROOT / 'data/assistant/skills'
    manifest = json.loads((folder / 'index.json').read_text())
    assert manifest['schema'] == 'edi.assistant.skills/1', (
        'I17: shipped skill manifest is versioned'
    )
    assert len(manifest['skills']) == len(IDS) and {
        value['id'] for value in manifest['skills']
    } == set(IDS), 'I17: first prototype ships the three independently contracted resources'
    descriptor = next(value for value in manifest['skills'] if value['id'] == identity)
    assert descriptor['version'] == '1.0.0' and descriptor['path'] == identity + '/SKILL.md', (
        'I17: selected resource has the reviewed initial version and bounded package-relative path'
    )
    raw = (folder / descriptor['path']).read_bytes()
    assert raw and hashlib.sha256(raw).hexdigest() == descriptor['sha256'], (
        'I17: independent hash of actual shipped bytes matches versioned resource provenance'
    )
    return {
        'id': identity,
        'version': '1.0.0',
        'sha256': hashlib.sha256(raw).hexdigest(),
        'content': raw.decode('utf-8'),
    }


def test_default_real_project_guidance_is_in_projectless_disclosure_before_any_send(host):
    observed = host.command('inspect')
    assert observed['context'].get('skills') == [shipped('project-assistance')], (
        'I17: actual guidance content/version/hash is disclosed before any provider request'
    )
    assert not observed['requests'], 'I17: local disclosure performs no provider action'
    context = observed['context']
    assert (
        context['project'] is None
        and all(context.get(name) == [] for name in ['structures', 'datasets', 'parameters'])
        and context.get('relations') == {'aliases': [], 'constraints': []}
    ), 'I1/I17: projectless metadata stays explicit and valid without invented fit readiness'


@pytest.mark.parametrize('identity', IDS)
def test_explicit_idle_selection_sends_exact_content_through_same_inspection_context(
    host, identity
):
    host.command('attach', id='project-A')
    host.connect()
    selected = host.user('select_skill', id=identity)
    assert selected['reply']['ok'], (
        'I17: actual existing command selects the declared workflow idle'
    )
    expected = [shipped(identity)]
    assert selected['context'].get('skills') == expected, (
        'I17: explicit workflow selection supplies the actual resource, never a URL-only label'
    )
    sent = host.user(
        'message',
        text='Use the explicitly selected workflow to inspect current data',
        connection_id='connection-A',
        model=protocol.MODEL,
        effort='high',
    )
    assert sent['reply']['ok'], 'I17: supported selected content admits the ordinary trusted turn'
    request = sent['requests'][-1]
    assert (
        request['context'] == selected['context'] and request['context']['skills'] == expected
    ), 'I17: outgoing snapshot equals the disclosed context including actual selected content/hash'
    inspected = host.tool('inspect_project', call_id='skill-context-read')
    outcome = [
        e
        for e in inspected['events']
        if e.get('type') == 'tool_result' and e.get('call_id') == 'skill-context-read'
    ]
    assert (
        inspected['reply']['ok']
        and len(outcome) == 1
        and outcome[0]['result'] == request['context']
    ), 'I1/I17: read-only inspect_project uses that same exact current context serializer'
    assert inspected['snapshot'] == selected['snapshot'] and inspected['apply_count'] == 0, (
        'I2/I17: selecting workflow guidance and reading it grants no scientific mutation'
    )
    declared = {tool['name'] for tool in request['tools']}
    assert not declared.intersection({
        'create_project',
        'import_fullprof',
        'import_gsas',
        'inspect_parameters',
        'read_skill',
    }), 'I17: resource prose cannot invent executable converter/create tools or recursive includes'


@pytest.mark.parametrize('identity', ['unknown-resource', '', None, 17])
def test_unknown_or_malformed_workflow_selection_refuses_atomically(host, identity):
    before = host.command('inspect')
    refused = host.user('select_skill', id=identity)
    assert not refused['reply']['ok'], 'I17: only exact shipped skill identities can be selected'
    assert refused['context'] == before['context'] and refused['snapshot'] == before['snapshot'], (
        'I17: malformed/unavailable selection cannot replace guidance or current scientific state'
    )
    assert not refused['requests'], 'I17: invalid resource selection performs no provider action'


def test_busy_workflow_selection_cannot_rebind_active_consent_or_request(host):
    started = host.start()
    binding = host.binding()
    refused = host.user('select_skill', id='fullprof-intake')
    assert not refused['reply']['ok'] and refused['reply']['code'] == 'edi.assistant.busy', (
        'I17: active work cannot acquire a different workflow/consent through idle-only selection'
    )
    assert refused['context'] == started['context'] and host.binding() == binding, (
        'I17: busy selection preserves exact active context and request authority'
    )
    assert len(refused['requests']) == len(started['requests']), (
        'I17: refused workflow change cannot issue a hidden replacement request'
    )
